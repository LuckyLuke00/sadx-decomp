"""Give each source file the compiler flags of its code group, for check.py.

write_codegen_groups() checks the rows of data/codegen-groups.csv and writes
build/codegen-groups.cmake, which CMakeLists.txt includes. A file's group is the one
that its FUNCTION, TEMPLATE and SYNTHETIC annotations sit in.
"""

import functools
import itertools
import re
import sys
from pathlib import Path

import osutil
import progress
import project

ROOT = progress.ROOT
GROUPS_CMAKE = project.BUILD / "codegen-groups.cmake"
UNBUILT_SOURCES = (".cc", ".cxx", ".c++", ".asm", ".s", ".rc")  # code that CMakeLists.txt would skip


@functools.cache
def function_marker() -> re.Pattern:
    """Annotations for code that has to match. STUB, GLOBAL and LIBRARY lines don't pick flags."""
    target = project.game_config().target
    return re.compile(rf"^\s*//\s*(?:FUNCTION|TEMPLATE|SYNTHETIC):\s*{target}\s+(0x[0-9a-fA-F]+)", re.MULTILINE)


def pools_strings(flags: list[str]) -> bool:
    """Whether MSVC pools strings with these flags."""
    return "/GF-" not in flags and any(flag in flags for flag in ("/GF", "/O1", "/O2"))


def check_group_rows(groups: list[dict]) -> None:
    """Stop if a row has flags that cl would split wrongly, or two rows overlap or disagree."""
    where = progress.CODEGEN_GROUPS.relative_to(ROOT).as_posix()
    for group in groups:
        if any(mark in group["flags"] for mark in '";'):
            sys.exit(f"{where}: group {group['group']} has a quote or semicolon in its flags. "
                     "Flags are split at spaces, so each must be one plain word.")
    for first, second in itertools.combinations(groups, 2):
        if first["start"] < second["end"] and second["start"] < first["end"]:
            sys.exit(f"{where}: the rows of groups {first['group']} and {second['group']} overlap.")
        if first["group"] == second["group"] and (first["kind"], first["flags"]) != (second["kind"], second["flags"]):
            sys.exit(f"{where}: the rows of group {first['group']} differ in kind or flags.")


def source_properties(groups: list[dict]) -> list[str]:
    """One CMake line for each .c and .cpp file in src/ that has FUNCTIONs."""
    lines = []
    for path in sorted((ROOT / "src").rglob("*")):
        source = path.relative_to(ROOT).as_posix()
        if path.suffix in UNBUILT_SOURCES:
            sys.exit(f"{source}: CMakeLists.txt builds only .c and .cpp files.")
        if path.suffix not in (".c", ".cpp"):
            continue
        group = file_group(source, read_source(path), groups)
        if group is None:
            continue
        options = ";".join(group["flags"].split())
        lines.append(f'set_source_files_properties("{source}" PROPERTIES COMPILE_OPTIONS "{options}")'
                     f'  # group {group["group"]}')
    return lines


def write_codegen_groups() -> None:
    """Give each source file the compiler flags of the code group its FUNCTIONs sit in.

    STUB and GLOBAL lines don't count. A file without FUNCTIONs keeps the base flags.
    """
    groups = progress.load_codegen_groups()
    check_group_rows(groups)
    header = f"# Generated by tools/check.py from {progress.CODEGEN_GROUPS.relative_to(ROOT).as_posix()}. Do not edit."
    lines = [header, *source_properties(groups)]
    osutil.write_if_changed(GROUPS_CMAKE, "\n".join(lines) + "\n")


def read_source(path: Path) -> str:
    """A source file's text. Sources are UTF-8 without a byte order mark, which is how reccmp reads them."""
    source = path.relative_to(ROOT).as_posix()
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError as error:
        sys.exit(f"{source} is not UTF-8 ({error.reason} at byte {error.start}). Save it as UTF-8.")
    if text.startswith("\ufeff"):
        sys.exit(f"{source} starts with a byte order mark. Save it as UTF-8 without one.")
    return text


def file_group(source: str, text: str, groups: list[dict]) -> dict | None:
    """The game code group of a file's FUNCTIONs, or None if it has none. Stops if they are not all in one."""
    found = {}  # group name: (group, first address in it)
    for address in function_marker().findall(text):
        group = progress.codegen_group(groups, int(address, 16))
        if group is None:
            sys.exit(f"{source}: {address} is outside every code group in {progress.CODEGEN_GROUPS.relative_to(ROOT)}")
        found.setdefault(group["group"], (group, address))
    if not found:
        return None
    if len(found) > 1:
        spread = ", ".join(f"{name} ({address})" for name, (_, address) in found.items())
        sys.exit(f"{source} has FUNCTIONs from code groups {spread}. Each group has its own compiler "
                 "flags, so one file may hold only one group: split the file.")
    group, address = next(iter(found.values()))
    if group["kind"] != "game":
        sys.exit(f"{source}: {address} is in the {group['group']} library range. "
                 "Code in library ranges is not decompiled.")
    return group
